-- Sample data for the local dev server: the `shop` database the mockups show.
-- Deterministic (setseed), so screenshots and tests see the same rows each time.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TYPE order_status AS ENUM ('pending', 'paid', 'shipped', 'delivered', 'cancelled');
CREATE TYPE payment_method AS ENUM ('pix', 'credit_card', 'boleto');

CREATE TABLE categories (
  id        int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name      text NOT NULL,
  parent_id int8 REFERENCES categories (id)
);

CREATE TABLE customers (
  id               int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
  name             text NOT NULL,
  email            citext NOT NULL UNIQUE,
  city             text,
  state            char(2),
  marketing_opt_in bool NOT NULL DEFAULT false,
  created_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE addresses (
  id          int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 5001),
  customer_id int8 NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
  street      text NOT NULL,
  city        text NOT NULL,
  state       char(2) NOT NULL,
  postal_code text NOT NULL
);

CREATE TABLE products (
  id          int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 101),
  sku         text NOT NULL UNIQUE,
  name        text NOT NULL,
  category_id int8 REFERENCES categories (id),
  price       numeric(12,2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE orders (
  id                  int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
  number              text NOT NULL UNIQUE,
  customer_id         int8 NOT NULL REFERENCES customers (id) ON DELETE RESTRICT,
  status              order_status NOT NULL DEFAULT 'pending',
  total               numeric(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  currency            char(3) NOT NULL DEFAULT 'BRL',
  placed_at           timestamptz NOT NULL DEFAULT now(),
  shipped_at          timestamptz,
  shipping_address_id int8 REFERENCES addresses (id) ON DELETE SET NULL,
  metadata            jsonb NOT NULL DEFAULT '{}',
  notes               text,
  updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX orders_customer_id_idx ON orders (customer_id);
CREATE INDEX orders_placed_at_idx ON orders (placed_at DESC);
CREATE INDEX orders_metadata_gin ON orders USING gin (metadata jsonb_path_ops);

CREATE TABLE order_items (
  id         int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  order_id   int8 NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  product_id int8 NOT NULL REFERENCES products (id),
  quantity   int4 NOT NULL CHECK (quantity > 0),
  unit_price numeric(12,2) NOT NULL
);
CREATE INDEX order_items_order_id_idx ON order_items (order_id);

CREATE TABLE payments (
  id       int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  order_id int8 NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  method   payment_method NOT NULL,
  amount   numeric(12,2) NOT NULL,
  paid_at  timestamptz NOT NULL
);

CREATE TABLE reviews (
  id          int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  product_id  int8 NOT NULL REFERENCES products (id),
  customer_id int8 NOT NULL REFERENCES customers (id),
  rating      int2 NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body        text
);

-- One of each type the grid has to show, for the type tests.
CREATE TABLE type_samples (
  id          int4 PRIMARY KEY,
  a_uuid      uuid,
  an_interval interval,
  a_range     int4range,
  tags        text[],
  scores      int4[],
  a_bytea     bytea,
  an_inet     inet,
  a_date      date,
  a_time      time,
  a_float     float8,
  a_json      json,
  a_money     money,
  a_bit       bit varying(8)
);

CREATE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;
CREATE TRIGGER orders_set_updated_at BEFORE UPDATE ON orders
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE FUNCTION order_total(order_id int8) RETURNS numeric LANGUAGE sql STABLE AS $$
  SELECT coalesce(sum(quantity * unit_price), 0) FROM order_items WHERE order_items.order_id = $1;
$$;

