INSERT INTO order_items (order_id, product_id, quantity, unit_price)
SELECT o.id, p.id, 1 + floor(random() * 3)::int, p.price
FROM orders o
CROSS JOIN LATERAL generate_series(1, 1 + (o.id * 7) % 3) AS i
JOIN products p ON p.id = 101 + (o.id * 13 + i * 5) % 7;

UPDATE orders o SET total = order_total(o.id);

