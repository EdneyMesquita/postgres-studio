CREATE VIEW order_totals AS
  SELECT o.id, o.number, o.status, sum(oi.quantity * oi.unit_price) AS items_total
  FROM orders o JOIN order_items oi ON oi.order_id = o.id
  GROUP BY o.id;

CREATE VIEW active_customers AS
  SELECT c.* FROM customers c
  WHERE EXISTS (SELECT 1 FROM orders o WHERE o.customer_id = c.id AND o.placed_at > now() - interval '90 days');

CREATE MATERIALIZED VIEW daily_revenue AS
  SELECT date_trunc('day', placed_at)::date AS day, count(*) AS orders, sum(total) AS revenue
  FROM orders WHERE status <> 'cancelled' GROUP BY 1;

