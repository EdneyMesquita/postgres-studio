-- Hypertables, columnstore, continuous aggregates and a failing job for the TimescaleDB tests.
CREATE EXTENSION IF NOT EXISTS timescaledb;

-- Hypertable with the new by_range API, 31 days of data from 10 devices every 30 seconds.
CREATE TABLE metrics (
  time      timestamptz NOT NULL,
  device_id int NOT NULL,
  cpu       double precision,
  mem       double precision
);
SELECT create_hypertable('metrics', by_range('time', INTERVAL '1 day'));
CREATE INDEX metrics_device_time_idx ON metrics (device_id, time DESC);
INSERT INTO metrics (time, device_id, cpu, mem)
SELECT t, d, random() * 100, random() * 16384
FROM generate_series(now() - INTERVAL '31 days', now(), INTERVAL '30 seconds') AS t
CROSS JOIN generate_series(1, 10) AS d;

-- Columnstore: older chunks are converted now and by the policy from then on.
ALTER TABLE metrics SET (timescaledb.enable_columnstore = true, timescaledb.segmentby = 'device_id', timescaledb.orderby = 'time DESC');
CALL add_columnstore_policy('metrics', after => INTERVAL '7 days');
SELECT count(*) FROM (SELECT compress_chunk(c, true) FROM show_chunks('metrics', older_than => INTERVAL '7 days') c) x;

SELECT add_retention_policy('metrics', drop_after => INTERVAL '90 days');

-- Hypertable with the old positional API, 120 days of events so some chunks are older than 60 days.
CREATE TABLE events (
  id      bigint GENERATED BY DEFAULT AS IDENTITY,
  at      timestamptz NOT NULL,
  kind    text NOT NULL,
  payload jsonb,
  PRIMARY KEY (id, at)
);
SELECT create_hypertable('events', 'at', chunk_time_interval => INTERVAL '7 days');
INSERT INTO events (at, kind, payload)
SELECT now() - (random() * INTERVAL '120 days'),
       (ARRAY['page_view', 'add_to_cart', 'checkout', 'signup'])[1 + n % 4],
       jsonb_build_object('n', n)
FROM generate_series(1, 20000) AS n;

-- Continuous aggregate with a refresh policy, materialized once for the last 31 days.
CREATE MATERIALIZED VIEW metrics_hourly WITH (timescaledb.continuous) AS
SELECT time_bucket('1 hour', time) AS bucket, device_id, avg(cpu) AS avg_cpu, max(mem) AS max_mem
FROM metrics
GROUP BY 1, 2
WITH NO DATA;
SELECT add_continuous_aggregate_policy('metrics_hourly', start_offset => INTERVAL '3 days', end_offset => INTERVAL '1 hour', schedule_interval => INTERVAL '30 minutes');
CALL refresh_continuous_aggregate('metrics_hourly', now() - INTERVAL '31 days', now() - INTERVAL '1 hour');

-- Hierarchical continuous aggregate on top of metrics_hourly, with real-time on.
CREATE MATERIALIZED VIEW metrics_daily WITH (timescaledb.continuous) AS
SELECT time_bucket('1 day', bucket) AS day, device_id, avg(avg_cpu) AS avg_cpu
FROM metrics_hourly
GROUP BY 1, 2
WITH NO DATA;
ALTER MATERIALIZED VIEW metrics_daily SET (timescaledb.materialized_only = false);
CALL refresh_continuous_aggregate('metrics_daily', now() - INTERVAL '31 days', now());

-- Continuous aggregate that is never refreshed and has no policy.
CREATE MATERIALIZED VIEW events_daily WITH (timescaledb.continuous) AS
SELECT time_bucket('1 day', at) AS day, kind, count(*) AS total
FROM events
GROUP BY 1, 2
WITH NO DATA;

-- A user-defined job that always fails.
CREATE PROCEDURE failing_job(job_id int, config jsonb) LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'boom from job %', job_id;
END
$$;
SELECT add_job('failing_job', '1 hour', initial_start => now());

-- A plain table next to the hypertables.
CREATE TABLE devices (
  id   int PRIMARY KEY,
  name text NOT NULL
);
INSERT INTO devices (id, name)
SELECT g, 'device-' || g FROM generate_series(1, 10) AS g;

-- Quoted names: a schema and a hypertable with uppercase and spaces.
CREATE SCHEMA "Telemetry";
CREATE TABLE "Telemetry"."Sensor Readings" (
  "Time" timestamptz NOT NULL,
  value  float8
);
SELECT create_hypertable('"Telemetry"."Sensor Readings"', by_range('Time', INTERVAL '1 day'));
INSERT INTO "Telemetry"."Sensor Readings" ("Time", value)
SELECT t, random() * 100
FROM generate_series(now() - INTERVAL '5 days', now(), INTERVAL '1 minute') AS t;

