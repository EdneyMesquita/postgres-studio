-- A second database, so the explorer and the per-database clients have something to switch to.
CREATE DATABASE analytics;
\connect analytics

CREATE TABLE events (
  id      int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name    text NOT NULL,
  at      timestamptz NOT NULL DEFAULT now(),
  payload jsonb
);
INSERT INTO events (name, at, payload)
SELECT (ARRAY['page_view','add_to_cart','checkout','signup'])[1 + n % 4],
       now() - (n || ' minutes')::interval,
       jsonb_build_object('n', n)
FROM generate_series(1, 500) AS n;

CREATE TABLE sessions (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  started_at timestamptz NOT NULL DEFAULT now(),
  pages      int4 NOT NULL DEFAULT 1
);
INSERT INTO sessions (pages) SELECT 1 + n % 9 FROM generate_series(1, 120) AS n;
